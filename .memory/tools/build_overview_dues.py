def q(ch, key):
    """按 (章, 唯一定位子串) 取该章的完整引语。"""
    hits = [x for x in QUOTES.get(ch, []) if key in x]
    if len(hits) != 1:
        raise SystemExit(f"❌ ch{ch:02d} 定位 {key!r} 命中 {len(hits)} 条")
    return hits[0]


def w(name, body):
    p = os.path.join(BOOK, name)
    open(p, "w", encoding="utf-8").write(body)
    n = body.count(chr(0xfffd))
    print(f"{'❌' if n else '✅'} {p}  ({len(body.encode('utf-8'))} bytes, U+FFFD={n})")
    if n:
        raise SystemExit("总览里有 U+FFFD，必须先修")


