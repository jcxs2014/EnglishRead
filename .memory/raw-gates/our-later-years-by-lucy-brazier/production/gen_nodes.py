def block_text(ch, n):
    path = os.path.join(BOOK, [f for f in os.listdir(BOOK) if f.startswith(ch + " ")][0])
    s = open(path, encoding="utf-8").read()
    m = re.search(r'> \*\*原句 %d:\*\* "(.*?)"\n' % n, s, re.S)
    if not m:
        raise SystemExit("missing %s Q%d" % (ch, n))
    return m.group(1)


def main():
    out = ['---', '状态: 未读', 'modified: "2026-10-27"', '---', '', '# 情感节点', '',
           '> 本书没有单一主人公，情感线由「一群人的共同决定」推进：一封广告信、一块陶牌、一次跌倒、一句「我没用了」、一场葬礼、一笔十八年的账。节点按时间与情绪推进排列，编号在同一文件内连续。', '']
    idx = 0
    for title, summary, quotes in NODES:
        out.append("## " + title)
        out.append('')
        out.append("**叙事概括：** " + summary)
        out.append('')
        for ch, n in quotes:
            out.append('> %s "%s"（%s）' % (CIRCLED[idx], block_text(ch, n), ch))
            idx += 1
        out.append('')
    path = os.path.join(BOOK, "00_情感节点.md")
    open(path, "w", encoding="utf-8").write("\n".join(out).rstrip() + "\n")
    print("wrote", path, idx, "quotes")


if __name__ == "__main__":
    main()
